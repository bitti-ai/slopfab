"""Generate byte-range tables for the two hash-locked legacy Torch checkpoints.

Usage: python tools/syncnet_manifest.py build/syncnet-reference src/syncnet
No torch dependency; pickle globals are restricted to inert tensor descriptions.
Runtime never invokes this parser or a pickle interpreter.
"""
import collections
import hashlib
import io
import pathlib
import pickle
import struct
import sys

MODELS = {
    "syncnet_v2.model": ("syncnet", "961e8696f888fce4f3f3a6c3d5b3267cf5b343100b238e79b2659bff2c605442"),
    "sfd_face.pth": ("s3fd", "d54a87c2b7543b64729c9a25eafd188da15fd3f6e02f0ecec76ae1b30d86c491"),
}


def tensor(storage, offset, shape, stride, *unused):
    return storage, offset, shape, stride


class Reader(pickle.Unpickler):
    def find_class(self, module, name):
        if (module, name) == ("collections", "OrderedDict"):
            return collections.OrderedDict
        if module == "torch._utils" and name in ("_rebuild_tensor", "_rebuild_tensor_v2"):
            return tensor
        if (module, name) == ("torch", "FloatStorage"):
            return "float32"
        raise ValueError(f"Forbidden global: {module}.{name}")

    def persistent_load(self, value):
        assert value[0] == "storage" and value[1] == "float32"
        assert value[5] is None
        return value[2], value[4]


def generate(source, output):
    for filename, (name, digest) in MODELS.items():
        data = (source / filename).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"Wrong SHA256: {filename}")
        stream = io.BytesIO(data)
        load = lambda: Reader(stream).load()
        assert load() == 119547037146038801333356
        assert load() == 1001
        assert load()["little_endian"]
        state = load()
        keys = load()
        ranges = {}
        for key in keys:
            count, = struct.unpack("<Q", stream.read(8))
            ranges[key] = stream.tell(), count
            stream.seek(count * 4, 1)
        assert stream.tell() == len(data)
        lines = ["// Generated by tools/syncnet_manifest.py; do not edit.",
                 f'// SHA256 {digest}', f'constexpr size_t {name}_size = {len(data)};',
                 f'constexpr const char* {name}_hash = "{digest}";',
                 f'const Entry {name}_entries[] = {{']
        for key, (storage, offset, shape, stride) in state.items():
            count = 1
            for dim, step in zip(reversed(shape), reversed(stride)):
                assert step == count
                count *= dim
            start, size = ranges[storage[0]]
            assert size == storage[1] and 0 <= offset and offset + count <= size
            dims = ", ".join(map(str, shape))
            lines.append(f'  {{"{key}", {start + offset * 4}, {{{dims}}}}},')
        lines.append("};\n")
        output.mkdir(parents=True, exist_ok=True)
        (output / (name + "_manifest.inc")).write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    generate(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
