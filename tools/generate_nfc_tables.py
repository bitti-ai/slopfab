"""Regenerate the portable tokenizer NFC tables from Python's Unicode database."""
import pathlib
import unicodedata as u

out = [f"// Generated by tools/generate_nfc_tables.py; Unicode {u.unidata_version}.\n"]
decompositions, classes, compositions = [], [], []
for cp in range(0x110000):
    char = chr(cp)
    cc = u.combining(char)
    if cc:
        classes.append((cp, cc))
    decomp = u.decomposition(char)
    if decomp and not decomp.startswith("<"):
        parts = [int(x, 16) for x in decomp.split()]
        decompositions.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
        if len(parts) == 2 and u.normalize("NFC", "".join(map(chr, parts))) == char:
            compositions.append((*parts, cp))
for name, rows in [("decompositions", decompositions), ("classes", classes),
                   ("compositions", sorted(compositions))]:
    out.append(f"static constexpr uint32_t {name}[][{'2' if name == 'classes' else '3'}] = {{\n")
    out.extend("  {" + ",".join(hex(v) for v in row) + "},\n" for row in rows)
    out.append("};\n")
pathlib.Path(__file__).resolve().parents[1].joinpath("src/text/nfc_tables.inc").write_text("".join(out))
